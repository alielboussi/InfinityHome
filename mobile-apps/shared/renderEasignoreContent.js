/**
 * EAS Build collects files from the git repo root. Each Expo app gets a .easignore
 * that keeps only that app folder + mobile-apps/shared (see app.config.js requires).
 */

const MOBILE_APP_SLUGS = Object.freeze([
  'orders',
  'carpentry-workshop',
  'painting-workshop',
  'warehouse-catalog',
  'warehouse-delivery',
  'warehouse-upholstery',
  'customer-credit',
  'lusaka-stock',
]);

function renderMonorepoEasignore(keepSlug) {
  const slug = String(keepSlug || '').trim();
  if (!MOBILE_APP_SLUGS.includes(slug)) {
    throw new Error(`Unknown mobile app slug: ${slug}`);
  }
  const lines = [
    '# Generated by mobile-apps/scripts/syncEasignore.js',
    `# EAS upload: keep mobile-apps/${slug}/ + mobile-apps/shared/ only.`,
    '# https://docs.expo.dev/build-reference/easignore/',
    '',
    '# --- Web monorepo ---',
    '/src/',
    '/api/',
    '/scripts/',
    '/docs/',
    '/public/',
    '/build/',
    '/coverage/',
    '/backups/',
    '/.vercel/',
    '/.cursor/',
  ];
  for (const other of MOBILE_APP_SLUGS) {
    if (other !== slug) {
      lines.push(`/mobile-apps/${other}/`);
    }
  }
  lines.push(
    '',
    '# --- Never upload dependencies / local build output ---',
    '**/node_modules/',
    '**/.expo/',
    '**/.expo-bundle-verify/',
    '**/.expo-bundle-verify*/',
    '**/.expo-export-test/',
    '**/.expo-export*/',
    '**/dist/',
    '**/dist-eas*/',
    '**/web-build/',
    '**/android/',
    '**/ios/',
    '*.jks',
    '*.p8',
    '*.p12',
    '*.key',
    '*.mobileprovision',
    '',
    `# --- ${slug} ---`,
    `/mobile-apps/${slug}/android/`,
    `/mobile-apps/${slug}/.expo-bundle-verify/`,
    `/mobile-apps/${slug}/.expo-bundle-verify-*/`,
    `/mobile-apps/${slug}/dist/`,
    `/mobile-apps/${slug}/dist-eas-*/`,
    '',
  );
  return `${lines.join('\n')}`;
}

module.exports = {
  MOBILE_APP_SLUGS,
  renderMonorepoEasignore,
};