const CI_TERMS = new Map(
  Object.entries(ARABIC_TERMS).map(([k, v]) => [k.toLowerCase(), v]),
);

export function lookupStaticArabic(text) {
  const s = String(text ?? '').trim();
  if (!s) return '';
  if (CI_TERMS.has(s.toLowerCase())) return CI_TERMS.get(s.toLowerCase());
  return '';
}

export function fallbackTranslatePhraseToArabic(text) {
  const s = String(text ?? '').trim();
  if (!s) return '';
  const direct = lookupStaticArabic(s);
  if (direct) return direct;
  let out = s;
  for (const [regex, ar] of WORD_FALLBACKS) {
    out = out.replace(regex, ar);
  }
  if (/[A-Za-z]/.test(out)) {
    out = out
      .split(/\s+/)
      .map((tok) => {
        if (!/[A-Za-z]/.test(tok)) return tok;
        const sub = lookupStaticArabic(tok);
        if (sub) return sub;
        let piece = tok;
        for (const [regex, ar] of WORD_FALLBACKS) {
          piece = piece.replace(regex, ar);
        }
        return piece;
      })
      .join(' ');
  }
  return out;
}

const WESTERN_TO_ARABIC_INDIC = Object.freeze({
  0: '٠',
  1: '١',
  2: '٢',
  3: '٣',
  4: '٤',
  5: '٥',
  6: '٦',
  7: '٧',
  8: '٨',
  9: '٩',
});

/** Eastern Arabic numerals (٠–٩) for workshop-facing Arabic UI/PDF. */
export function toArabicIndicDigits(value) {
  return String(value ?? '').replace(/[0-9]/g, (d) => WESTERN_TO_ARABIC_INDIC[d] || d);
}

export function formatNumeralsForLocale(value, locale) {
  const s = String(value ?? '');
  if (locale !== 'ar') return s;
  return toArabicIndicDigits(s);
}

export function translateTermToArabic(term, serverMap = {}) {
  const s = String(term ?? '').trim();
  if (!s) return '';
  if (serverMap[s]) return serverMap[s];
  const direct = lookupStaticArabic(s);
  if (direct) return direct;
  return fallbackTranslatePhraseToArabic(s);
}

const UNIT_AR = new Map([
  ['pc(s)', 'قطعة'],
  ['pc', 'قطعة'],
  ['pcs', 'قطع'],
  ['piece', 'قطعة'],
  ['pieces', 'قطع'],
  ['m', 'م'],
  ['meter', 'متر'],
  ['meters', 'متر'],
  ['sqm', 'م²'],
  ['set', 'طقم'],
  ['sets', 'أطقم'],
]);

export function translateQtyUnitLabel(unitAbbr, locale, serverMap = {}) {
  const raw = String(unitAbbr ?? '').trim();
  if (!raw || locale !== 'ar') return raw;
  const key = raw.toLowerCase().replace(/\s+/g, '');
  if (UNIT_AR.has(key)) return UNIT_AR.get(key);
  return translateTermToArabic(raw, serverMap) || raw;
}

export function formatQuoteLineQtyLabel(qty, unitAbbr, locale, serverMap = {}) {
  const q = formatNumeralsForLocale(String(qty ?? 1).trim(), locale);
  const unit = translateQtyUnitLabel(unitAbbr, locale, serverMap);
  if (unit) return `${q} ${unit}`;
  return q;
}

/** L × W × H (cm) with Arabic-Indic digits when `locale === 'ar'`. */
export function formatQuoteDimensionsCmDisplay(line, locale = 'en') {
  const trim = (v) => (v != null ? String(v).trim() : '');
  const l = trim(line?.dim_l_cm);
  const w = trim(line?.dim_w_cm);
  const h = trim(line?.dim_h_cm);
  if (l && w && h) {
    const joined = `${l} × ${w} × ${h}`;
    return formatNumeralsForLocale(joined, locale);
  }
  const legacy = trim(line?.dimensions_lwh);
  if (legacy) {
    const normalized = legacy.replace(/\s*[x×*]\s*/gi, ' × ');
    return formatNumeralsForLocale(normalized, locale);
  }
  const partial = [l, w, h].filter(Boolean);
  if (!partial.length) return '';
  return formatNumeralsForLocale(partial.join(' × '), locale);
}

function normalizeAccessoriesList(raw) {
  if (!raw) return [];
  const arr = Array.isArray(raw) ? raw : String(raw).split(',');
  return arr.map((s) => String(s ?? '').trim()).filter(Boolean);
}

/**
 * Collect English phrases from quote lines for batch server translation.
 */
export function collectProductionQuoteArabicPhrases(lines = []) {
  const set = new Set();
  const add = (v) => {
    const s = String(v ?? '').trim();
    if (s) set.add(s);
  };
  for (const line of lines || []) {
    const meta = line?.metadata && typeof line.metadata === 'object' ? line.metadata : {};
    add(line?.name || line?.product_name || line?.quote_product_name);
    add(line?.description || meta.description);
    add(line?.wood || meta.wood);
    add(line?.foam_type || meta.foam_type);
    add(line?.color_code || meta.color_code);
    add(line?.leather_code || meta.leather_code);
    for (const acc of normalizeAccessoriesList(line?.accessories ?? meta.accessories)) {
      add(acc);
    }
  }
  return [...set];
}

export function displayQuoteFieldValue(locale, value, serverMap = {}) {
  const raw = String(value ?? '').trim();
  if (!raw) return '';
  if (locale !== 'ar') return raw;
  return translateTermToArabic(raw, serverMap);
}
