const CI_TERMS = new Map(
  Object.entries(ARABIC_TERMS).map(([k, v]) => [k.toLowerCase(), v]),
);

export function lookupStaticArabic(text) {
  const s = String(text ?? '').trim();
  if (!s) return '';
  if (CI_TERMS.has(s.toLowerCase())) return CI_TERMS.get(s.toLowerCase());
  return '';
}

export function fallbackTranslatePhraseToArabic(text) {
  const s = String(text ?? '').trim();
  if (!s) return '';
  const direct = lookupStaticArabic(s);
  if (direct) return direct;
  let out = s;
  for (const [regex, ar] of WORD_FALLBACKS) {
    out = out.replace(regex, ar);
  }
  if (/[A-Za-z]/.test(out)) {
    out = out
      .split(/\s+/)
      .map((tok) => {
        if (!/[A-Za-z]/.test(tok)) return tok;
        const sub = lookupStaticArabic(tok);
        if (sub) return sub;
        let piece = tok;
        for (const [regex, ar] of WORD_FALLBACKS) {
          piece = piece.replace(regex, ar);
        }
        return piece;
      })
      .join(' ');
  }
  return out;
}

const WESTERN_TO_ARABIC_INDIC = Object.freeze({
  0: '٠',
  1: '١',
  2: '٢',
  3: '٣',
  4: '٤',
  5: '٥',
  6: '٦',
  7: '٧',
  8: '٨',
  9: '٩',
});

/** Eastern Arabic numerals (٠–٩) for workshop-facing Arabic UI/PDF. */
export function toArabicIndicDigits(value) {
  return String(value ?? '').replace(/[0-9]/g, (d) => WESTERN_TO_ARABIC_INDIC[d] || d);
}

export function formatNumeralsForLocale(value, locale) {
  const s = String(value ?? '');
  if (locale !== 'ar') return s;
  return toArabicIndicDigits(s);
}

const ALLOWED_LATIN_IN_ARABIC = /\b(RAL|MDF|HD|PU|USB|LED|HDMI|CPU|cm|CAT)\b/gi;

/** Normalize common quote typos / variants before Arabic lookup (PDF + workshop apps). */
export function normalizeQuoteEnglishPhrase(value) {
  return String(value ?? '')
    .replace(/\bv[ei]neer\b/gi, 'veneer')
    .replace(/\s+/g, ' ')
    .trim();
}

/** False when Arabic line still contains stray English words (partial word-by-word fallback). */
export function phraseStillHasEnglishWords(text) {
  const stripped = String(text ?? '').replace(ALLOWED_LATIN_IN_ARABIC, ' ');
  return /[A-Za-z]{2,}/.test(stripped);
}

function lookupServerTranslation(s, serverMap = {}) {
  if (serverMap[s]) return String(serverMap[s]).trim();
  const lower = s.toLowerCase();
  for (const [key, val] of Object.entries(serverMap)) {
    if (String(key).toLowerCase() === lower && val) return String(val).trim();
  }
  const titled = s.charAt(0).toUpperCase() + s.slice(1);
  if (serverMap[titled]) return String(serverMap[titled]).trim();
  return '';
}

export function translateProductLineNameToArabic(nameEn, serverMap = {}) {
  const raw = String(nameEn ?? '').trim();
  if (!raw) return '';
  const direct = translateTermToArabic(raw, serverMap);
  if (direct) return direct;
  const m = raw.match(/^(.+?)\s*\(([^)]+)\)\s*$/);
  if (!m) return '';
  const base = String(m[1] || '').trim();
  const inner = String(m[2] || '').trim();
  const baseAr = translateTermToArabic(base, serverMap);
  const innerAr = translateTermToArabic(inner, serverMap);
  if (baseAr && innerAr) return `${baseAr} (${innerAr})`;
  return '';
}

export function translateSlashDimensionDescriptionToArabic(text, serverMap = {}) {
  const s = normalizeQuoteEnglishPhrase(String(text ?? '').trim());
  if (!s) return '';
  const triple = s.match(
    /\blength\s*(\d+)\s*cm?\s*[/\s,]+\s*height\s*(\d+)\s*cm?\s*[/\s,]+\s*depth\s*(\d+)\s*cm?/i,
  );
  if (triple) {
    return `الطول ${toArabicIndicDigits(triple[1])} سم / الارتفاع ${toArabicIndicDigits(triple[2])} سم / العمق ${toArabicIndicDigits(triple[3])} سم`;
  }
  const lwh = s.match(
    /\blength\s*(\d+)\s*cm?\s*[/\s,]+\s*height\s*(\d+)\s*cm?\s*[/\s,]+\s*width\s*(\d+)\s*cm?/i,
  );
  if (lwh) {
    return `الطول ${toArabicIndicDigits(lwh[1])} سم / الارتفاع ${toArabicIndicDigits(lwh[2])} سم / العرض ${toArabicIndicDigits(lwh[3])} سم`;
  }
  return translateTermToArabic(s, serverMap);
}

function resolveFactoryOrderArabicPhrase(phrase, map = {}) {
  const raw = String(phrase || '').trim();
  if (!raw) return '';
  if (/\blength\s*\d+/i.test(raw) && /\bheight\s*\d+/i.test(raw)) {
    const dimAr = translateSlashDimensionDescriptionToArabic(raw, map);
    if (dimAr && !phraseStillHasEnglishWords(dimAr)) return dimAr;
  }
  if (raw.includes('(') && raw.includes(')')) {
    const nameAr = translateProductLineNameToArabic(raw, map);
    if (nameAr && !phraseStillHasEnglishWords(nameAr)) return nameAr;
  }
  const ar = translateTermToArabic(raw, map);
  return ar && !phraseStillHasEnglishWords(ar) ? ar : '';
}

export function translateTermToArabic(term, serverMap = {}) {
  const raw = String(term ?? '').trim();
  if (!raw) return '';
  const s = normalizeQuoteEnglishPhrase(raw);
  const fromServer =
    lookupServerTranslation(s, serverMap) || (s !== raw ? lookupServerTranslation(raw, serverMap) : '');
  if (fromServer && !phraseStillHasEnglishWords(fromServer)) return fromServer;
  const direct = lookupStaticArabic(s);
  if (direct) return direct;
  const titled = s.charAt(0).toUpperCase() + s.slice(1);
  const directTitled = titled !== s ? lookupStaticArabic(titled) : '';
  if (directTitled) return directTitled;
  const fb = fallbackTranslatePhraseToArabic(s);
  if (!phraseStillHasEnglishWords(fb)) return fb;
  return '';
}

